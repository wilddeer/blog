/*
 * Генератор иконки хинкаля — tools/khinkali-gen.cjs
 *
 * Что это:
 *   Скрипт, который генерирует _includes/svg/khinkali.svg (иконка у заголовка
 *   «2022...2023» в списке постов). Складки хинкаля — не нарисованные руками
 *   кривые, а «меридианы» на поверхности приплюснутой луковицы с закруткой:
 *   макушка повёрнута относительно низа, поворот затухает к дну. S-образность
 *   складок возникает сама из проекции спирали на объём.
 *
 * Как пользоваться:
 *   node tools/khinkali-gen.cjs
 *   Скрипт перезаписывает _includes/svg/khinkali.svg. Файл руками не править —
 *   правки перетрутся при следующем запуске. Меняем параметры здесь и запускаем.
 *
 * Система координат:
 *   viewBox="100 100 824 824", вертикальная ось симметрии x=512.
 *   Тело: горловина y≈342, самое широкое место y≈614 (x 277..747), дно y≈792.
 *
 * Устройство:
 *   - w(y) — полуширина тела на высоте y, кусочная функция из трёх сегментов
 *     (горловина, плечи, дно). ВАЖНО: контур тела нарисован отдельным путём
 *     (bodyPath ниже); если меняешь контур — синхронно поправь w(y), иначе
 *     складки перестанут попадать в стенки.
 *   - fold(...) — одна складка: семплируем x = 512 + w(y)·sin(θ0 + τ(u) − ...)
 *     каждые 8px по y и кодируем цепочкой квадратичных Безье через середины
 *     отрезков (гладкость C1). u ∈ [0..1] — доля пройденной длины складки.
 *   - τ(u) — закрутка: T·(1 − smoothstep((u − plateau)/(1 − plateau))).
 *     Наверху折 held на максимуме (складка «идёт по стенке»), затем плавно
 *     затухает до нуля к низу.
 *
 * Параметры fold(theta0, T, dy0, dy1, endPull, pullExp, nudgeX, peel, plateau, cutY, ampK, bumpB):
 *   theta0   — «долгота» складки в радианах: 0 = центральная, минус = левее,
 *              плюс = правее. sin(theta0) задаёт базовое положение на теле.
 *   T        — амплитуда закрутки (сейчас 0.42 у всех): на сколько радиан
 *              макушка повёрнута относительно низа.
 *   dy0, dy1 — сдвиг точки начала/конца по вертикали (от базовых значений).
 *              ВНИМАНИЕ: dy1 меняет длину, от которой считается u, то есть
 *              двигает всю динамику складки. Чтобы просто укоротить конец,
 *              используй cutY.
 *   endPull  — увод хвоста от стенки: доворот внутрь, набирающий силу с 45%
 *              длины. 0 = выключено.
 *   pullExp  — экспонента профиля endPull. 1 = равномерно; >1 — кривизна
 *              нарастает к самому кончику (кончик «загибается по часовой»).
 *   nudgeX   — сдвиг верхушки по горизонтали в px, затухает за первые 15%
 *              длины. Нужен, чтобы спрятать торчащую из стенки верхушку
 *              (сейчас +7 у второй справа).
 *   peel     — доворот внутрь в первых 28% длины: складка резче «отлипает»
 *              от стенки наверху. Сейчас не используется (0).
 *   plateau  — доля длины, на которой закрутка держится максимальной
 *              (по умолчанию 0.06). Больше — складка дольше сливается со
 *              стенкой и «выходит» из неё ниже (у самой правой 0.52).
 *   cutY     — обрезать складку на этой абсолютной высоте y, НЕ меняя
 *              параметризацию остального (в отличие от dy1).
 *   ampK     — усиление изгибов: отклонение кривой от хорды между её концами
 *              умножается на ampK (концы неподвижны). 0/1 = выключено.
 *              Пробовали 1.6 — откатили, оставлено на будущее.
 *   bumpB    — альтернативный профиль для центральной складки: прямой участок
 *              от хвостика + «пузо» вправо с пиком у широкого места, амплитуда
 *              bumpB px. Пробовали 38..52 — откатили, оставлено на будущее.
 *
 * Пенёк (хвостик):
 *   Цилиндрик со срезом-овалом (виден верх под углом): задний обод — дуга
 *   поверх контура, передний обод — сплющенный эллипс (rx 56, ry 17).
 *   Наклон 2.5° «запекается» поворотом точек вокруг основания (512, 336) —
 *   в готовом SVG никаких transform. Высота: верх обода y≈298, основание 336.
 *
 * Толщины штрихов: контур и пенёк 30, передний обод пенька 22, складки 20.
 */

const fs = require('fs');
const path = require('path');

// Полуширина тела на высоте y. Три сегмента: горловина (степенная),
// плечи (синус), дно (четверть эллипса). Синхронизирована с bodyPath.
function w(y) {
  if (y < 478) { const u = (y - 342) / 136; return 56 + 86 * Math.pow(Math.max(u, 0), 1.7); }
  if (y < 614) { const u = (y - 478) / 136; return 142 + 93 * Math.sin(Math.PI / 2 * u); }
  const u = (y - 614) / 178; return 235 * Math.sqrt(Math.max(0, 1 - u * u));
}

const smoothstep = t => t <= 0 ? 0 : t >= 1 ? 1 : t * t * (3 - 2 * t);

function fold(theta0, T, dy0, dy1, endPull, pullExp, nudgeX, peel, plateau, cutY, ampK, bumpB) {
  const y0 = 358 + 14 * Math.abs(Math.sin(theta0)) + dy0;
  const y1 = 762 - 48 * Math.abs(Math.sin(theta0)) + dy1;
  const pts = [];
  for (let y = y0; y <= Math.min(y1 + 1, cutY || 9999); y += 8) {
    const u = (y - y0) / (y1 - y0);

    if (bumpB) {
      // прямой спуск от хвостика, затем пузо вправо с пиком у широкого места
      const startOff = w(y0) * Math.sin(T);
      const belly = Math.pow(Math.sin(Math.PI * Math.pow(Math.min(1, Math.max(0, (u - 0.08) / 0.92)), 0.88)), 2);
      const off = startOff * (1 - smoothstep((u - 0.25) / 0.6)) + bumpB * belly;
      pts.push([512 + off, y]);
      continue;
    }

    const p = plateau || 0.06;
    const tau = T * (1 - smoothstep((u - p) / (1 - p)));
    const s = Math.max(0, Math.min(1, (u - 0.45) / 0.55));
    const pull = (endPull || 0) * Math.pow(s, pullExp || 1) * Math.sign(theta0);
    const pl = (peel || 0) * smoothstep(u / 0.28) * Math.sign(theta0);
    const nudge = (nudgeX || 0) * (1 - smoothstep(u / 0.15));
    pts.push([512 + w(y) * Math.sin(theta0 + tau - pull - pl) + nudge, y]);
  }

  // усиление изгибов: растягиваем отклонение от хорды, концы на месте
  if (ampK && ampK !== 1 && pts.length > 2) {
    const [x0, ya] = pts[0], [x1, yb] = pts[pts.length - 1];
    for (let i = 1; i < pts.length - 1; i++) {
      const t = (pts[i][1] - ya) / (yb - ya);
      const chord = x0 + (x1 - x0) * t;
      pts[i][0] = chord + ampK * (pts[i][0] - chord);
    }
  }

  // точки -> гладкий путь: квадратичные Безье через середины отрезков
  let d = 'M' + pts[0][0].toFixed(1) + ' ' + pts[0][1].toFixed(1);
  for (let i = 1; i < pts.length - 1; i++) {
    const mx = (pts[i][0] + pts[i + 1][0]) / 2, my = (pts[i][1] + pts[i + 1][1]) / 2;
    d += 'Q' + pts[i][0].toFixed(1) + ' ' + pts[i][1].toFixed(1) + ' ' + mx.toFixed(1) + ' ' + my.toFixed(1);
  }
  const last = pts[pts.length - 1];
  d += 'L' + last[0].toFixed(1) + ' ' + last[1].toFixed(1);
  return d;
}

// Пенёк: наклон 2.5° запекаем поворотом точек вокруг основания (512, 336)
const th = 2.5 * Math.PI / 180, cos = Math.cos(th), sin = Math.sin(th);
const rot = ([x, y]) => [(512 + (x - 512) * cos - (y - 336) * sin).toFixed(1), (336 + (x - 512) * sin + (y - 336) * cos).toFixed(1)];
const [bl, tl, tr, br] = [[456, 336], [456, 298], [568, 298], [568, 336]].map(rot);
const stumpBack = `M${bl[0]} ${bl[1]}L${tl[0]} ${tl[1]}A56 17 2.5 0 1 ${tr[0]} ${tr[1]}L${br[0]} ${br[1]}`;
const stumpRim = `M${tl[0]} ${tl[1]}A56 17 2.5 0 0 ${tr[0]} ${tr[1]}`;

// Контур тела (синхронизирован с w(y), см. выше)
const bodyPath = 'M456 342C454 396 424 442 370 478C320 512 277 550 277 614C277 716 372 792 512 792C652 792 747 716 747 614C747 550 704 512 654 478C600 442 570 396 568 342';

// Набор складок, слева направо.
//                theta   T     dy0  dy1  pull  pExp nudge peel plateau cutY ampK bumpB
const inner = [
  fold(-0.96,     0.42,   4,   -8,   0.06, 1,   0,    0,   0,      0,   0,   0),
  fold(-0.52,     0.42,  -6,    4,   0,    1,   0,    0,   0,      0,   0,   0),
  fold(0,         0.42,   8,  -18,   0,    1,   0,    0,   0,      0,   0,   0),
  fold(0.52,      0.42,   0,   10,   0,    1,   7,    0,   0,      0,   0,   0),
  fold(1.05,      0.42,   6,  -26,   0.26, 2.6, 0,    0,   0.52,   668, 0,   0)
];
const pleats = inner.map(d => '        <path d="' + d + '"/>').join('\n');

const svg = `<svg class="icon" xmlns="http://www.w3.org/2000/svg" viewBox="100 100 824 824">
    <g fill="none" stroke="currentColor" stroke-width="30" stroke-linecap="round" stroke-linejoin="round">
        <path d="${stumpBack}"/>
        <path stroke-width="22" d="${stumpRim}"/>
        <path d="${bodyPath}"/>
        <g stroke-width="20">
${pleats}
        </g>
    </g>
</svg>
`;

const out = path.join(__dirname, '../_includes/svg/khinkali.svg');
fs.writeFileSync(out, svg);
console.log('saved', out);
